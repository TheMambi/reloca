// The seven checklist tasks a lease creates, and the dates they fall on.
//
// One definition serves both the first seeding and the refresh after a lease
// edit (app/lease/actions.ts), so the checklist cannot drift from the lease.

import { addDaysIso } from "@/lib/dates";
import { noticeTerm } from "@/lib/lease/notice-term";
import { depositReturnDays, leaseStateCode, stateName } from "@/lib/lease/deposit-rules";
import type { LeaseTerms } from "@/schemas/lease";

// Lease task offsets (days). Operational defaults.
const INSURANCE_LEAD_BEFORE_LEASE_END = 14;
const DESTINATION_INSURANCE_LEAD = 7;
const ORIGIN_POLICY_CANCEL_OFFSET = 7; // days after move-out
const CONDITION_DOC_LEAD = 3; // days before move-out

export type LeaseTask = {
  title: string;
  description: string | null;
  due_date: string | null;
  order_index: number;
  /** Recognizes this task's stored row when its title depends on the lease. */
  titlePattern?: RegExp;
};

type LeaseDates = Pick<
  LeaseTerms,
  "city" | "lease_end_date" | "notice_days_required" | "target_move_out_date"
>;

export function noticeSendByDate(lease: LeaseDates): string {
  return addDaysIso(lease.lease_end_date, -lease.notice_days_required);
}

/** Last day for the deposit accounting, or null when the state's rule is not on file. */
export function depositDeadline(lease: LeaseDates): string | null {
  const days = depositReturnDays(leaseStateCode(lease.city));
  if (days === null || !lease.target_move_out_date) return null;
  return addDaysIso(lease.target_move_out_date, days);
}

export function buildLeaseTasks(lease: LeaseDates): LeaseTask[] {
  const moveOut = lease.target_move_out_date ?? lease.lease_end_date;
  const state = leaseStateCode(lease.city);
  const depositDays = depositReturnDays(state);

  return [
    {
      title: `Send ${noticeTerm(lease.notice_days_required)} to vacate`,
      titlePattern: /^Send (\d+-day )?notice to vacate$/,
      description:
        "Reply to renewal email with last-day-in-apartment date. Generated by /lease notice composer.",
      due_date: noticeSendByDate(lease),
      order_index: 0,
    },
    {
      title: "Confirm origin renter's insurance to lease end",
      description:
        "Keep coverage active through lease end and list your landlord as an interested party if the lease requires it.",
      due_date: addDaysIso(lease.lease_end_date, -INSURANCE_LEAD_BEFORE_LEASE_END),
      order_index: 1,
    },
    {
      title: "Set up destination renter's insurance",
      description:
        "Coverage starts on or before move-out date. Liability/property minimums per destination requirements.",
      due_date: addDaysIso(moveOut, -DESTINATION_INSURANCE_LEAD),
      order_index: 2,
    },
    {
      title: "Cancel/transfer origin policy",
      description: "Avoid double-billing after move-out.",
      due_date: addDaysIso(moveOut, ORIGIN_POLICY_CANCEL_OFFSET),
      order_index: 3,
    },
    {
      title: "Document apartment condition (photo + video)",
      description: "Move-out walkthrough — protects deposit recovery.",
      due_date: addDaysIso(moveOut, -CONDITION_DOC_LEAD),
      order_index: 4,
    },
    {
      title: "Return keys + provide forwarding address",
      description: "Confirms move-out per landlord procedure.",
      due_date: moveOut,
      order_index: 5,
    },
    {
      title: "Track deposit return",
      description:
        state && depositDays !== null
          ? `${stateName(state)}: landlord must itemize within ${depositDays} days of move-out.`
          : "The deadline for returning or itemizing a deposit differs by state. Check your state's rule and note the date.",
      due_date: depositDays !== null ? addDaysIso(moveOut, depositDays) : null,
      order_index: 6,
    },
  ];
}
